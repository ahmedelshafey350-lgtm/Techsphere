# Process all 310 projects for documentation publishing
$adminEmail = "admin@techsphere.local"
$adminPassword = "AdminPass123!"
$supabaseUrl = "https://gzzmrwdolrhjhzpovytg.supabase.co"
$apiKey = "sb_publishable_GC9KQfkI3qw_dIOU82Bfrw_EEMGUqlL"

# Get admin token
Write-Host "Getting admin token..."
$signinBody = @{email=$adminEmail; password=$adminPassword} | ConvertTo-Json
$signin = Invoke-RestMethod -Uri "$supabaseUrl/auth/v1/token?grant_type=password" -Method POST -Headers @{apikey=$apiKey; "Content-Type"="application/json"} -Body $signinBody -ErrorAction Stop
$adminToken = $signin.access_token
Write-Host "Admin token obtained"

# Track results
$successCount = 0
$failureCount = 0
$processedCount = 0
$totalProjects = 310
$startTime = Get-Date

Write-Host "Starting documentation processing for $totalProjects projects..."
Write-Host "============================================="

# Process projects in batches of 10 to avoid rate limiting
for ($batch = 0; $batch -lt [Math]::Ceiling($totalProjects / 10); $batch++) {
    $startIdx = $batch * 10
    $endIdx = [Math]::Min(($batch + 1) * 10, $totalProjects)
    
    Write-Host ""
    Write-Host "Processing batch $($batch + 1): Projects $startIdx-$($endIdx - 1)"
    
    for ($i = $startIdx; $i -lt $endIdx; $i++) {
        $processedCount++
        Write-Host ""
        Write-Host "[$processedCount/$totalProjects] Processing project $($i + 1)..."
        
        # Get project details via SQL
        $sqlResult = npx supabase db query --linked --project-ref gzzmrwdolrhjhzpovytg "SELECT id, project_code, title_en, title_ar, public_description_en, source_document FROM public.service_projects ORDER BY project_code LIMIT 1 OFFSET $i;" 2>&1 | Where-Object { $_ -notmatch "Initialising login role" -and $_ -notmatch "node.exe" }
        
        # Parse SQL result to extract project data
        $projectData = $null
        foreach ($line in $sqlResult) {
            if ($line -match '\| (.+?) \| (.+?) \| (.+?) \| (.+?) \| (.+?) \| (.+?) \|') {
                $projectData = @{
                    id = $matches[1].Trim()
                    project_code = $matches[2].Trim()
                    title_en = $matches[3].Trim()
                    title_ar = $matches[4].Trim()
                    public_description_en = $matches[5].Trim()
                    source_document = $matches[6].Trim()
                }
                break
            }
        }
        
        if (-not $projectData) {
            Write-Host "  ❌ Failed to get project data for project $i"
            $failureCount++
            continue
        }
        
        Write-Host "  Project: $($projectData.project_code) - $($projectData.title_en)"
        
        # Generate project-specific documentation
        $documentation = Generate-ProjectDocumentation $projectData
        
        # Publish documentation
        $publishBody = @{
            project_code = $projectData.project_code
            documentation = $documentation
            version = "1.0.0"
            changelog_en = "Initial comprehensive documentation publication"
            changelog_ar = "نشر التوثيق الشامل الأول"
            source_document = "Generated by Techsphere documentation system"
        } | ConvertTo-Json -Depth 10
        
        try {
            $response = Invoke-RestMethod -Uri "$supabaseUrl/functions/v1/document_publish" -Method POST -Headers @{
                Authorization = "Bearer $adminToken"
                "Content-Type" = "application/json"
            } -Body $publishBody -ErrorAction Stop
            
            Write-Host "  ✅ SUCCESS: Document ID $($response.document_version_id)"
            $successCount++
        }
        catch {
            if ($_.Exception.Message -match "409") {
                Write-Host "  ⚠️  CONFLICT: Documentation already exists for this project"
                $successCount++  # Count as success since it already exists
            } else {
                Write-Host "  ❌ FAILED: $($_.Exception.Message)"
                $failureCount++
            }
        }
        
        # Small delay to avoid rate limiting
        Start-Sleep -Milliseconds 300
    }
}

# Final summary
$endTime = Get-Date
$duration = $endTime - $startTime

Write-Host ""
Write-Host "============================================="
Write-Host "DOCUMENTATION PROCESSING COMPLETE"
Write-Host "============================================="
Write-Host "Total projects: $totalProjects"
Write-Host "Successfully processed: $successCount"
Write-Host "Failed: $failureCount"
Write-Host "Success rate: $(($successCount / $totalProjects * 100).ToString("0.00"))%"
Write-Host "Duration: $($duration.ToString("hh\:mm\:ss"))"

# Verify final status
Write-Host ""
Write-Host "Verifying final status..."
$verification = npx supabase db query --linked --project-ref gzzmrwdolrhjhzpovytg "SELECT COUNT(*) as total_docs FROM public.service_project_document_versions;" 2>&1 | Where-Object { $_ -notmatch "Initialising login role" -and $_ -notmatch "node.exe" }
Write-Host "Total document versions created: $verification"

