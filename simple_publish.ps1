# Simple script to publish documentation for projects

$adminEmail = "admin@techsphere.local"
$adminPassword = "AdminPass123!"
$supabaseUrl = "https://gzzmrwdolrhjhzpovytg.supabase.co"
$apiKey = "sb_publishable_GC9KQfkI3qw_dIOU82Bfrw_EEMGUqlL"

# Get admin token
Write-Host "Getting admin token..."
$signinBody = @{
    email = $adminEmail
    password = $adminPassword
} | ConvertTo-Json

$signin = Invoke-RestMethod -Uri "$supabaseUrl/auth/v1/token?grant_type=password" -Method POST -Headers @{
    apikey = $apiKey
    "Content-Type" = "application/json"
} -Body $signinBody -ErrorAction Stop

$adminToken = $signin.access_token
Write-Host "Token obtained successfully"

# Get all projects
Write-Host "Fetching projects..."
$headers = @{
    apikey = $apiKey
    "Content-Type" = "application/json"
}

$projectsResponse = Invoke-RestMethod -Uri "$supabaseUrl/rest/v1/service_projects?select=id,project_code,slug,category_id,title_ar,title_en,public_description_en,difficulty,source_document,status,catalog_visible&order=project_code&limit=1000" -Method GET -Headers $headers -ErrorAction Stop
$projects = $projectsResponse.value
Write-Host "Found $($projects.Count) projects"

# Process first 5 projects for testing
$successCount = 0
$failureCount = 0

for ($i = 0; $i -lt [Math]::Min(5, $projects.Count); $i++) {
    $project = $projects[$i]
    Write-Host "Processing project $($i + 1)/5: $($project.project_code) - $($project.title_en)"
    
    # Create basic documentation
    $documentation = @{
        title = $project.title_en
        arabic_title = $project.title_ar
        description = $project.public_description_en
        technical_overview = "Engineering project with practical implementation"
        implementation_guide = "Follow project specifications and implement according to requirements"
        components_required = @("Development tools", "Materials as needed", "Testing equipment")
        troubleshooting = @("Check specifications", "Verify connections", "Test functionality")
        learning_outcomes = @("Understand project concepts", "Develop practical skills", "Gain experience")
    }
    
    # Add project-specific details based on type
    $projectType = $project.project_code.Substring(4, 3)
    switch ($projectType) {
        "DLG" {
            $documentation.technical_overview = "Digital logic circuit implementation"
            $documentation.implementation_guide = "Implement logic gates and verify with truth tables"
            $documentation.components_required = @("Logic ICs", "Breadboard", "LEDs", "Resistors")
        }
        "ESP" {
            $documentation.technical_overview = "IoT project with ESP32 microcontroller"
            $documentation.implementation_guide = "Set up development environment and implement sensor integration"
            $documentation.components_required = @("ESP32 board", "Sensors", "Power supply")
        }
        "EE-" {
            $documentation.technical_overview = "Electronic circuit design"
            $documentation.implementation_guide = "Design and build electronic circuits"
            $documentation.components_required = @("Electronic components", "PCB", "Testing equipment")
        }
        default {
            $documentation.technical_overview = "Engineering project implementation"
            $documentation.implementation_guide = "Follow project specifications and implement"
        }
    }
    
    $publishBody = @{
        project_code = $project.project_code
        documentation = $documentation
        version = "1.0.0"
        changelog_en = "Initial comprehensive documentation publication"
        changelog_ar = "نشر التوثيق الشامل الأول"
        source_document = "Generated by Techsphere documentation system"
    } | ConvertTo-Json -Depth 10
    
    try {
        $response = Invoke-RestMethod -Uri "$supabaseUrl/functions/v1/document_publish" -Method POST -Headers @{
            Authorization = "Bearer $adminToken"
            "Content-Type" = "application/json"
        } -Body $publishBody -ErrorAction Stop
        
        Write-Host "  ✓ Successfully published - Document ID: $($response.document_version_id)"
        $successCount++
    }
    catch {
        Write-Host "  ✗ Failed: $($_.Exception.Message)"
        $failureCount++
    }
    
    # Small delay to avoid rate limiting
    Start-Sleep -Milliseconds 200
}

Write-Host ""
Write-Host "=== Results ==="
Write-Host "Processed projects: 5"
Write-Host "Successful: $successCount"
Write-Host "Failed: $failureCount"