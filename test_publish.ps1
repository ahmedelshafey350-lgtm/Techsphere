# Test script to publish documentation

$adminEmail = "admin@techsphere.local"
$adminPassword = "AdminPass123!"
$supabaseUrl = "https://gzzmrwdolrhjhzpovytg.supabase.co"
$apiKey = "sb_publishable_GC9KQfkI3qw_dIOU82Bfrw_EEMGUqlL"

# Get admin token
Write-Host "Getting admin token..."
$signinBody = @{
    email = $adminEmail
    password = $adminPassword
} | ConvertTo-Json

$signin = Invoke-RestMethod -Uri "$supabaseUrl/auth/v1/token?grant_type=password" -Method POST -Headers @{
    apikey = $apiKey
    "Content-Type" = "application/json"
} -Body $signinBody -ErrorAction Stop

$adminToken = $signin.access_token
Write-Host "Token obtained"

# Get projects
Write-Host "Fetching projects..."
$headers = @{
    apikey = $apiKey
    "Content-Type" = "application/json"
}

$projectsResponse = Invoke-RestMethod -Uri "$supabaseUrl/rest/v1/service_projects?select=id,project_code,title_en&order=project_code&limit=10" -Method GET -Headers $headers -ErrorAction Stop
$projects = $projectsResponse.value
Write-Host "Found $($projects.Count) projects"

# Process each project
foreach ($project in $projects) {
    Write-Host "Processing: $($project.project_code) - $($project.title_en)"
    
    $documentation = @{
        title = $project.title_en
        description = "Engineering project implementation"
        technical_overview = "Practical engineering project with detailed implementation"
        implementation_guide = "Follow specifications and implement step by step"
        troubleshooting = @("Check specifications", "Verify connections", "Test functionality")
        learning_outcomes = @("Understand concepts", "Develop skills", "Gain experience")
    }
    
    $publishBody = @{
        project_code = $project.project_code
        documentation = $documentation
        version = "1.0.0"
        changelog_en = "Initial documentation"
        source_document = "Generated by Techsphere"
    } | ConvertTo-Json -Depth 10
    
    try {
        $response = Invoke-RestMethod -Uri "$supabaseUrl/functions/v1/document_publish" -Method POST -Headers @{
            Authorization = "Bearer $adminToken"
            "Content-Type" = "application/json"
        } -Body $publishBody -ErrorAction Stop
        
        Write-Host "  SUCCESS: $($response.document_version_id)"
    }
    catch {
        Write-Host "  FAILED: $($_.Exception.Message)"
    }
    
    Start-Sleep -Milliseconds 500
}

Write-Host "Done"